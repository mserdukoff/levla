function glossWord(language: LangCode, text: string, gloss: string, pos: string): Token {
  return {
    text,
    ws: language === "ja" ? "" : " ",
    is_word: true,
    lemma: text,
    morph: {
      lemma: text,
      pos,
      case: null,
      gender: null,
      number: null,
      tense: null,
      aspect: null,
      mood: null,
      reading: null,
      form: null,
    },
    gloss,
    level: "A2",
  };
}

function glossStop(text: string): Token {
  return { text, ws: /[。！？]/.test(text) ? "" : " ", is_word: false, lemma: null, morph: null, gloss: null, level: null };
}

