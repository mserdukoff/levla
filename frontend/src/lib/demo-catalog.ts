function tokensToText(tokens: Token[], language: LangCode): string {
  return tokens.map((t) => t.text + (t.ws ?? "")).join(language === "ja" ? "" : "").replace(/\s+$/, "");
}

function sampleLemmas(tokens: Token[], language: LangCode): string[] {
  const seen = new Set<string>();
  const out: string[] = [];
  for (const tok of tokens) {
    if (!tok.lemma || !isContentWord(tok, language) || seen.has(tok.lemma)) continue;
    seen.add(tok.lemma);
    out.push(tok.lemma);
    if (out.length >= 8) break;
  }
  return out;
}

