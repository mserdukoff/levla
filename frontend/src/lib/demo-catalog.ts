function calibration(language: LangCode, level: CefrLevel, tokens: Token[]): Calibration {
  const passport = PASSPORT[language][level];
  return {
    passed: true,
    attempts: 1,
    overlevel_lemma_rate: 0.03,
    subordinate_rate: level === "A1" ? 0 : level === "A2" ? 0.04 : 0.12,
    forbidden_case_rate: 0,
    forbidden_tense_rate: 0,
    forbidden_pos_rate: 0,
    flags: [],
    warnings: [],
    allowed_constructions: passport.allowed,
    banned_constructions: passport.banned,
    forbidden_used: [],
    sample_lemmas: sampleLemmas(tokens, language),
  };
}

function makePassage(opts: {
  id: string;
  language: LangCode;
  level: CefrLevel;
  topic: string;
  genre: string;
  title: string;
  tokens: Token[];
  translation: string;
  created_at: string;
  comprehension?: Passage["comprehension"];
  source_name?: string;
  source_url?: string | null;
  source_date?: string;
}): Passage {
  return {
    id: opts.id,
    language: opts.language,
    level: opts.level,
    topic: opts.topic,
    genre: opts.genre,
    title: opts.title,
    text: tokensToText(opts.tokens, opts.language),
    tokens: opts.tokens,
    calibration: calibration(opts.language, opts.level, opts.tokens),
    word_count: opts.tokens.filter((t) => t.is_word).length,
    created_at: opts.created_at,
    translation: opts.translation,
    comprehension: opts.comprehension,
    source_name: opts.source_name,
    source_url: opts.source_url,
    source_date: opts.source_date,
  };
}

function fromDemo(
  id: string,
  lang: LangCode,
  translation: string,
  created_at: string,
): Passage {
  const demo = DEMO[lang];
  return makePassage({
    id,
    language: lang,
    level: demo.level,
    topic: demo.topic,
    genre: "daily_life",
    title: demo.title,
    tokens: demo.tokens,
    translation,
    created_at,
  });
}

