ROOTS_OUT = ROOT / "data" / "roots" / "ar.json"

PEDAGOGICAL: dict[str, tuple[str, str]] = {}
ROOTS: dict[str, str] = {}


def add(level: str, pairs: list[tuple[str, str]]) -> None:
    for lemma, gloss in pairs:
        lemma = _norm(lemma)
        if lemma and lemma not in PEDAGOGICAL:
            PEDAGOGICAL[lemma] = (level, gloss.strip())


def root(letters: str, meaning: str) -> None:
    key = _norm(letters.replace(" ", ""))
    if key and key not in ROOTS:
        ROOTS[key] = meaning.strip()


